"""
Unicode CaseFolding.txt dosyasından C# tablosu üretir: src/Apfs.Core/Util/CaseFoldingTable.g.cs

Kullanılan durumlar: C (ortak) ve F (tam katlama). S (basit) ve T (Türkçe'ye özel) KULLANILMAZ.
Bu, APFS'in büyük/küçük harf duyarsız karşılaştırmasıyla uyumludur ve Türkçe için önemlidir:
  I  (U+0049) -> i
  İ  (U+0130) -> i + U+0307   (F)
  ı  (U+0131) -> eşleme yok  => "ı" ile "i" farklı adlardır
Kullanım:  python tools/gen_casefold.py [CaseFolding.txt yolu veya URL]
"""
import sys
import urllib.request

SOURCE = "https://www.unicode.org/Public/UCD/latest/ucd/CaseFolding.txt"
OUT = "src/Apfs.Core/Util/CaseFoldingTable.g.cs"


def load(src):
    if src.startswith("http"):
        with urllib.request.urlopen(src) as r:
            return r.read().decode("utf-8")
    with open(src, encoding="utf-8") as f:
        return f.read()


def main():
    text = load(sys.argv[1] if len(sys.argv) > 1 else SOURCE)
    version = next((l.strip("# \n") for l in text.splitlines() if l.startswith("# CaseFolding-")), "bilinmiyor")
    entries = {}
    for line in text.splitlines():
        line = line.split("#", 1)[0].strip()
        if not line:
            continue
        code, status, mapping = [p.strip() for p in line.split(";")[:3]]
        if status not in ("C", "F"):
            continue
        entries[int(code, 16)] = [int(c, 16) for c in mapping.split()]

    keys = sorted(entries)
    lines = [
        "// <auto-generated>",
        f"// tools/gen_casefold.py tarafından {version} dosyasından üretildi. Elle düzenlemeyin.",
        "// Kaynak: Unicode Character Database, CaseFolding.txt (Unicode License v3). Durumlar: C + F (S ve T hariç).",
        "// </auto-generated>",
        "namespace Apfs.Util;",
        "",
        "internal static partial class CaseFolding",
        "{",
        f"    internal const string UnicodeVersion = \"{version}\";",
        "",
        "    /// <summary>Katlanan kod noktaları (artan sırada).</summary>",
        "    private static readonly int[] Keys =",
        "    [",
    ]
    for i in range(0, len(keys), 12):
        lines.append("        " + ", ".join(f"0x{k:04X}" for k in keys[i:i + 12]) + ",")
    lines += [
        "    ];",
        "",
        "    /// <summary>Her anahtarın katlanmış hali (bir veya daha fazla kod noktası).</summary>",
        "    private static readonly int[][] Values =",
        "    [",
    ]
    for i in range(0, len(keys), 6):
        chunk = keys[i:i + 6]
        lines.append("        " + " ".join("[" + ", ".join(f"0x{c:04X}" for c in entries[k]) + "]," for k in chunk))
    lines += ["    ];", "}", ""]
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines))
    print(f"{OUT}: {len(keys)} giriş ({version})")


if __name__ == "__main__":
    main()
